// Regenerates src/lib/map-pin-art.ts: the 3D category art shrunk to 72px as data URIs, because the map WebView cannot read app assets.
// macOS only (uses sips). Run from the app root after changing assets/images/map-categories: node scripts/map-pin-art.mjs
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

const IDS = ['dining', 'cafe', 'nightlife', 'festival', 'events', 'places', 'housing', 'used', 'shopping', 'travel', 'bubble', 'visited'];
const dir = mkdtempSync(join(tmpdir(), 'pin-art-'));
const lines = IDS.map(id => {
  const out = join(dir, `${id}.png`);
  execFileSync('sips', ['-Z', '72', `assets/images/map-categories/${id}.png`, '--out', out], { stdio: 'ignore' });
  return `  ${id}: 'data:image/png;base64,${readFileSync(out).toString('base64')}',`;
});
writeFileSync('src/lib/map-pin-art.ts', `// Generated by scripts/map-pin-art.mjs from assets/images/map-categories (72px). Do not edit by hand.\nexport const MAP_PIN_ART = {\n${lines.join('\n')}\n} as const;\nexport type MapPinArt = keyof typeof MAP_PIN_ART;\n`);
