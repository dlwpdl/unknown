create function private.is_admin()
returns boolean
language sql
stable
security invoker
set search_path = ''
as $$
  select coalesce(
    (select auth.jwt() -> 'app_metadata' ->> 'role') = 'admin',
    false
  );
$$;

create function private.is_blocked_between(first_user uuid, second_user uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.blocks
    where (blocker_id = first_user and blocked_id = second_user)
       or (blocker_id = second_user and blocked_id = first_user)
  );
$$;

create function private.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

create function private.set_posted_on()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  profile_timezone text;
begin
  select city.timezone
  into profile_timezone
  from public.profiles as profile
  join public.cities as city on city.id = profile.city_id
  where profile.id = new.author_id;

  if profile_timezone is null then
    raise exception 'PROFILE_REQUIRED';
  end if;

  new.posted_on := (now() at time zone profile_timezone)::date;
  return new;
end;
$$;

create function private.update_post_reaction_count()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  affected_post uuid;
  affected_kind text;
  change integer;
begin
  if tg_op = 'INSERT' then
    affected_post := new.post_id;
    affected_kind := new.kind;
    change := 1;
  else
    affected_post := old.post_id;
    affected_kind := old.kind;
    change := -1;
  end if;

  if affected_kind = 'like' then
    update public.posts
    set like_count = greatest(0, like_count + change)
    where id = affected_post;
  else
    update public.posts
    set save_count = greatest(0, save_count + change)
    where id = affected_post;
  end if;
  if tg_op = 'INSERT' then return new; else return old; end if;
end;
$$;

create function private.update_comment_like_count()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  affected_comment uuid;
  change integer;
begin
  if tg_op = 'INSERT' then
    affected_comment := new.comment_id;
    change := 1;
  else
    affected_comment := old.comment_id;
    change := -1;
  end if;

  update public.comments
  set like_count = greatest(0, like_count + change)
  where id = affected_comment;
  if tg_op = 'INSERT' then return new; else return old; end if;
end;
$$;

create function private.update_post_comment_count()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  change integer := 0;
begin
  if tg_op = 'INSERT' then
    change := 1;
  elsif old.deleted_at is null and new.deleted_at is not null then
    change := -1;
  elsif old.deleted_at is not null and new.deleted_at is null then
    change := 1;
  end if;

  if change <> 0 then
    update public.posts
    set comment_count = greatest(0, comment_count + change)
    where id = new.post_id;
  end if;
  return new;
end;
$$;

