-- 글링 Supabase 백엔드 v1
-- 범위: 일상 글, 프로필, 반응, 1:1 대화, 신고와 관리자 검토.

create extension if not exists citext;

create schema if not exists private;
revoke all on schema private from public;

-- ───────────────────────── 기본 데이터 ─────────────────────────

create table public.cities (
  id text primary key,
  name text not null,
  province text not null,
  timezone text not null,
  is_open boolean not null default true
);

create table public.tags (
  id smallint generated by default as identity primary key,
  slug text not null unique,
  label text not null,
  sort_order smallint not null default 0
);

create table public.profiles (
  id uuid primary key references auth.users(id),
  nickname citext not null unique
    check (char_length(trim(nickname::text)) between 2 and 20),
  city_id text not null references public.cities(id),
  neighborhood text check (char_length(neighborhood) <= 40),
  bio text check (char_length(bio) <= 200),
  avatar_path text check (
    avatar_path is null or avatar_path like id::text || '/%'
  ),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- ───────────────────────── 일상 공유 ─────────────────────────

create table public.posts (
  id uuid primary key default gen_random_uuid(),
  author_id uuid not null references public.profiles(id),
  city_id text not null references public.cities(id),
  tag_id smallint not null references public.tags(id),
  title text not null
    check (char_length(trim(title)) between 1 and 80),
  body text not null
    check (char_length(trim(body)) between 1 and 4000),
  image_paths text[] not null default '{}'
    check (cardinality(image_paths) <= 4),
  status text not null default 'published'
    check (status in ('published', 'removed')),
  posted_on date not null,
  like_count integer not null default 0 check (like_count >= 0),
  save_count integer not null default 0 check (save_count >= 0),
  comment_count integer not null default 0 check (comment_count >= 0),
  view_count integer not null default 0 check (view_count >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (author_id, posted_on)
);

create index posts_feed_idx
  on public.posts (city_id, created_at desc, id desc)
  where status = 'published';
create index posts_author_idx
  on public.posts (author_id, created_at desc);

create table public.comments (
  id uuid primary key default gen_random_uuid(),
  post_id uuid not null references public.posts(id),
  author_id uuid not null references public.profiles(id),
  body text not null
    check (char_length(trim(body)) between 1 and 1000),
  like_count integer not null default 0 check (like_count >= 0),
  created_at timestamptz not null default now(),
  deleted_at timestamptz
);

create index comments_post_idx
  on public.comments (post_id, created_at, id);
create index comments_author_idx
  on public.comments (author_id, created_at desc);

create table public.post_reactions (
  post_id uuid not null references public.posts(id),
  user_id uuid not null references public.profiles(id),
  kind text not null check (kind in ('like', 'save')),
  created_at timestamptz not null default now(),
  primary key (post_id, user_id, kind)
);

create index post_reactions_user_idx
  on public.post_reactions (user_id, created_at desc);

create table public.comment_likes (
  comment_id uuid not null references public.comments(id),
  user_id uuid not null references public.profiles(id),
  created_at timestamptz not null default now(),
  primary key (comment_id, user_id)
);

create table public.post_views (
  post_id uuid not null references public.posts(id),
  user_id uuid not null references public.profiles(id),
  created_at timestamptz not null default now(),
  primary key (post_id, user_id)
);

-- ───────────────────────── 대화와 안전 ─────────────────────────

create table public.blocks (
  blocker_id uuid not null references public.profiles(id),
  blocked_id uuid not null references public.profiles(id),
  created_at timestamptz not null default now(),
  primary key (blocker_id, blocked_id),
  check (blocker_id <> blocked_id)
);

create table public.conversations (
  id uuid primary key default gen_random_uuid(),
  user_low_id uuid not null references public.profiles(id),
  user_high_id uuid not null references public.profiles(id),
  created_at timestamptz not null default now(),
  unique (user_low_id, user_high_id),
  check (user_low_id < user_high_id)
);

create index conversations_high_user_idx
  on public.conversations (user_high_id, created_at desc);
create index conversations_low_user_idx
  on public.conversations (user_low_id, created_at desc);

create table public.messages (
  id uuid primary key default gen_random_uuid(),
  conversation_id uuid not null references public.conversations(id),
  sender_id uuid not null references public.profiles(id),
  body text not null
    check (char_length(trim(body)) between 1 and 2000),
  created_at timestamptz not null default now()
);

create index messages_conversation_idx
  on public.messages (conversation_id, created_at desc, id desc);
create index messages_sender_idx
  on public.messages (sender_id, created_at desc);

create table public.reports (
  id uuid primary key default gen_random_uuid(),
  reporter_id uuid not null references public.profiles(id),
  reported_user_id uuid not null references public.profiles(id),
  target_type text not null
    check (target_type in ('user', 'post', 'comment', 'message')),
  target_id uuid not null,
  reason_code text not null
    check (reason_code in ('spam', 'harassment', 'hate', 'sexual', 'privacy', 'other')),
  details text check (char_length(details) <= 1000),
  status text not null default 'open'
    check (status in ('open', 'actioned', 'dismissed')),
  created_at timestamptz not null default now(),
  resolved_at timestamptz,
  resolved_by uuid references public.profiles(id),
  unique (reporter_id, target_type, target_id),
  check (reporter_id <> reported_user_id)
);

create index reports_queue_idx
  on public.reports (status, created_at);
create index reports_reported_user_idx
  on public.reports (reported_user_id, created_at desc);

create table public.moderation_actions (
  id uuid primary key default gen_random_uuid(),
  report_id uuid not null references public.reports(id),
  actor_id uuid not null references public.profiles(id),
  action text not null check (action in ('actioned', 'dismissed')),
  note text check (char_length(note) <= 1000),
  created_at timestamptz not null default now()
);

create index moderation_actions_report_idx
  on public.moderation_actions (report_id, created_at);

