create function public.start_conversation(other_user_id uuid)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_user_id uuid := auth.uid();
  low_user_id uuid;
  high_user_id uuid;
  conversation_id uuid;
begin
  if current_user_id is null then
    raise exception 'AUTH_REQUIRED';
  end if;
  if current_user_id = other_user_id then
    raise exception 'INVALID_RECIPIENT';
  end if;
  if not exists (select 1 from public.profiles where id = other_user_id) then
    raise exception 'USER_NOT_FOUND';
  end if;
  if private.is_blocked_between(current_user_id, other_user_id) then
    raise exception 'BLOCKED';
  end if;

  low_user_id := least(current_user_id, other_user_id);
  high_user_id := greatest(current_user_id, other_user_id);

  insert into public.conversations (user_low_id, user_high_id)
  values (low_user_id, high_user_id)
  on conflict (user_low_id, user_high_id) do nothing;

  select id into conversation_id
  from public.conversations
  where user_low_id = low_user_id and user_high_id = high_user_id;

  return conversation_id;
end;
$$;

create function public.send_message(conversation_id uuid, message_body text)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_user_id uuid := auth.uid();
  conversation public.conversations;
  other_user_id uuid;
  message_id uuid;
begin
  if current_user_id is null then
    raise exception 'AUTH_REQUIRED';
  end if;

  select * into conversation
  from public.conversations
  where id = conversation_id
    and current_user_id in (user_low_id, user_high_id);

  if conversation is null then
    raise exception 'CONVERSATION_NOT_FOUND';
  end if;

  other_user_id := case
    when conversation.user_low_id = current_user_id then conversation.user_high_id
    else conversation.user_low_id
  end;

  if private.is_blocked_between(current_user_id, other_user_id) then
    raise exception 'BLOCKED';
  end if;

  insert into public.messages (conversation_id, sender_id, body)
  values (conversation.id, current_user_id, message_body)
  returning id into message_id;

  return message_id;
end;
$$;

create function public.record_post_view(post_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_user_id uuid := auth.uid();
begin
  if current_user_id is null then
    raise exception 'AUTH_REQUIRED';
  end if;
  if not exists (
    select 1 from public.posts
    where id = post_id
      and (
        private.is_admin()
        or author_id = current_user_id
        or (
          status = 'published'
          and not private.is_blocked_between(current_user_id, author_id)
        )
      )
  ) then
    raise exception 'POST_NOT_FOUND';
  end if;

  insert into public.post_views (post_id, user_id)
  values (post_id, current_user_id)
  on conflict do nothing;

  if found then
    update public.posts
    set view_count = view_count + 1
    where id = post_id;
  end if;
end;
$$;

create function public.create_report(
  target_type text,
  target_id uuid,
  reason_code text,
  details text default null
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_user_id uuid := auth.uid();
  target_user_id uuid;
  report_id uuid;
begin
  if current_user_id is null then
    raise exception 'AUTH_REQUIRED';
  end if;
  if reason_code not in ('spam', 'harassment', 'hate', 'sexual', 'privacy', 'other') then
    raise exception 'INVALID_REASON';
  end if;

  case target_type
    when 'user' then
      select id into target_user_id from public.profiles where id = target_id;
    when 'post' then
      select author_id into target_user_id
      from public.posts
      where id = target_id
        and (
          private.is_admin()
          or (
            status = 'published'
            and not private.is_blocked_between(current_user_id, author_id)
          )
        );
    when 'comment' then
      select comment.author_id into target_user_id
      from public.comments as comment
      join public.posts as post on post.id = comment.post_id
      where comment.id = target_id
        and (
          private.is_admin()
          or (
            comment.deleted_at is null
            and post.status = 'published'
            and not private.is_blocked_between(current_user_id, comment.author_id)
          )
        );
    when 'message' then
      select message.sender_id into target_user_id
      from public.messages as message
      join public.conversations as conversation
        on conversation.id = message.conversation_id
      where message.id = target_id
        and (
          private.is_admin()
          or current_user_id in (
            conversation.user_low_id,
            conversation.user_high_id
          )
        );
    else
      raise exception 'INVALID_TARGET_TYPE';
  end case;

  if target_user_id is null then
    raise exception 'TARGET_NOT_FOUND';
  end if;
  if target_user_id = current_user_id then
    raise exception 'CANNOT_REPORT_SELF';
  end if;

  insert into public.reports (
    reporter_id,
    reported_user_id,
    target_type,
    target_id,
    reason_code,
    details
  )
  values (
    current_user_id,
    target_user_id,
    target_type,
    target_id,
    reason_code,
    details
  )
  returning id into report_id;

  return report_id;
end;
$$;

create function public.resolve_report(
  report_id uuid,
  resolution text,
  note text default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_user_id uuid := auth.uid();
begin
  if not private.is_admin() then
    raise exception 'ADMIN_REQUIRED';
  end if;
  if resolution not in ('actioned', 'dismissed') then
    raise exception 'INVALID_RESOLUTION';
  end if;

  update public.reports
  set status = resolution,
      resolved_at = now(),
      resolved_by = current_user_id
  where id = report_id and status = 'open';

  if not found then
    raise exception 'OPEN_REPORT_NOT_FOUND';
  end if;

  insert into public.moderation_actions (report_id, actor_id, action, note)
  values (report_id, current_user_id, resolution, note);
end;
$$;

